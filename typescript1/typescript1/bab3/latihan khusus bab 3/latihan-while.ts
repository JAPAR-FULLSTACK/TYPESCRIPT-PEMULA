console.log("=== 1. ANGKA 1 SAMPAI 20 (WHILE LOOP) ===");
let angka: number = 1;

while (angka <= 20) {
    console.log(`Angka: ${angka}`);
    angka++;
}

console.log("\n==========================================");

console.log("=== 2. ANGKA GANJIL 1 SAMPAI 19 (WHILE LOOP) ===");
let angkaGanjil: number = 1;

while (angkaGanjil <= 19) {
    console.log(`Angka ganjil: ${angkaGanjil}`);
    angkaGanjil += 2;
}